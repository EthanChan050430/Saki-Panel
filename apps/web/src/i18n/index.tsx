export function translateDomAttributeValue(value: string, language: PanelLanguage = "en-US"): string {
  return translateDomText(value, language);
}

export function applyPanelDomLanguage(language: PanelLanguage, root: ParentNode = document.body): void {
  if (root instanceof Node && shouldSkipDomLanguageNode(root)) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) =>
      shouldSkipDomLanguageNode(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
  });
  const textNodes: Text[] = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode as Text);
  }

  for (const node of textNodes) {
    if (!domTextOriginals.has(node)) {
      domTextOriginals.set(node, node.nodeValue ?? "");
    }
    const original = domTextOriginals.get(node) ?? "";
    const nextValue = translateDomText(original, language);
    if (node.nodeValue !== nextValue) {
      nodesBeingTranslated.add(node);
      node.nodeValue = nextValue;
    }
  }

  const elements = root instanceof Element ? [root, ...Array.from(root.querySelectorAll<HTMLElement>("*"))] : Array.from(root.querySelectorAll<HTMLElement>("*"));
  for (const element of elements) {
    if (shouldSkipDomLanguageNode(element)) continue;
    for (const attr of ["title", "aria-label", "placeholder"] as const) {
      const value = element.getAttribute(attr);
      if (value === null) continue;
      const originalKey = "data-i18n-original-" + attr;
      if (!element.hasAttribute(originalKey)) {
        element.setAttribute(originalKey, value);
      }
      const original = element.getAttribute(originalKey) ?? value;
      const nextValue = translateDomAttributeValue(original, language);
      if (element.getAttribute(attr) !== nextValue) {
        let attrs = attributesBeingTranslated.get(element);
        if (!attrs) {
          attrs = new Set<string>();
          attributesBeingTranslated.set(element, attrs);
        }
        attrs.add(attr);
        element.setAttribute(attr, nextValue);
      }
    }
  }
}
